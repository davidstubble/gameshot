import { Directory, File, Paths } from 'expo-file-system';
import * as Sharing from 'expo-sharing';

function safePdfName(name: string): string {
  const stem = (typeof name === 'string' ? name : 'GameShot-layout.pdf')
    .replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').replace(/\.+$/, '').slice(0, 120) || 'GameShot-layout';
  return stem.toLowerCase().endsWith('.pdf') ? stem : `${stem}.pdf`;
}

function uniqueCacheFile(folder: Directory, requestedName: string): File {
  const extensionAt = requestedName.toLowerCase().lastIndexOf('.pdf');
  const base = extensionAt > 0 ? requestedName.slice(0, extensionAt) : requestedName;
  for (let attempt = 0; attempt < 100; attempt++) {
    const suffix = attempt ? `-${attempt + 1}` : '';
    const candidate = new File(folder, `${base}${suffix}.pdf`);
    if (!candidate.exists) return candidate;
  }
  throw new Error('Too many PDF copies use this name. Choose a different name.');
}

/** Writes a new cache file then opens the system sheet; generated bytes never leave the device first. */
export async function downloadPdf(bytes: Uint8Array, name: string): Promise<void> {
  if (!(await Sharing.isAvailableAsync())) throw new Error('PDF sharing is unavailable on this device.');
  const folder = new Directory(Paths.cache, 'GameShot', 'pdf');
  folder.create({ intermediates: true, idempotent: true });
  const file = uniqueCacheFile(folder, safePdfName(name));
  file.create({ overwrite: false, intermediates: true });
  file.write(new Uint8Array(bytes));
  await Sharing.shareAsync(file.uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: 'Save or share GameShot layout PDF' });
}
